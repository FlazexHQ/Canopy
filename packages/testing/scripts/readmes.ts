function render(name: string, entry: Entry, description: string): string {
  const install = [`@canopy/${name}`, ...(entry.with ?? [])].join(" ")
  const guides = entry.guides
    .map(
      ([path, title]) =>
        `- [${title}](${REPOSITORY}/blob/master/apps/docs/src/content/docs/${path}.md)`,
    )
    .join("\n")
  return [
    MARKER,
    "",
    `# @canopy/${name}`,
    "",
    description,
    ...(entry.about === undefined ? [] : ["", entry.about]),
    "",
    `Part of [Canopy](${REPOSITORY}), an open source, self hostable backend platform for MongoDB. Nothing is`,
    "published to npm yet: until then, use it from a clone of the repository.",
    "",
    "## Install",
    "",
    "```bash",
    `bun add ${install}`,
    "```",
    "",
    "`pnpm add`, `yarn add` and `npm install` take the same names.",
    "",
    "## Use",
    "",
    ...(entry.setup === undefined ? [] : [...entry.setup, ""]),
    `\`\`\`${entry.lang ?? "ts"}`,
    entry.snippet,
    "```",
    "",
    "## Learn more",
    "",
    guides,
    "",
  ].join("\n")
}

let stale = 0
for (const [name, entry] of Object.entries(ENTRIES)) {
  const dir = join(root, "packages", name)
  const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
    description?: string
  }
  const text = render(name, entry, manifest.description ?? "")
  const path = join(dir, "README.md")
  const current = existsSync(path) ? readFileSync(path, "utf8").replaceAll("\r\n", "\n") : undefined
  if (current !== undefined && !current.startsWith(MARKER)) {
    process.stderr.write(`packages/${name}/README.md is written by hand; remove its entry here\n`)
    stale++
  } else if (current !== text) {
    if (check) {
      process.stderr.write(`packages/${name}/README.md is out of date\n`)
      stale++
    } else writeFileSync(path, text)
  }
}
if (stale > 0) {
  if (check) process.stderr.write("Run bun packages/testing/scripts/readmes.ts\n")
  process.exit(1)
}
process.stdout.write(
  `${Object.keys(ENTRIES).length} package READMEs ${check ? "are up to date" : "written"}\n`,
)
