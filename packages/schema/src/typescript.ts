import type { CollectionSchema, ObjectShape, ScalarType, Shape } from "./shape.ts"

/**
 * The TypeScript type of each BSON type as the client decodes it from relaxed EJSON: 64 bit integers small
 * enough for a double arrive as numbers.
 */
const SCALAR_TYPES: Readonly<Record<ScalarType, string>> = {
  string: "string",
  int: "number",
  double: "number",
  long: "number | Long",
  decimal: "Decimal128",
  bool: "boolean",
  date: "Date",
  objectId: "ObjectId",
  binData: "Binary",
  uuid: "Binary",
  null: "null",
  timestamp: "Timestamp",
  regex: "BSONRegExp",
  minKey: "MinKey",
  maxKey: "MaxKey",
  javascript: "unknown",
}

const IMPORTS = [
  "Binary",
  "BSONRegExp",
  "Decimal128",
  "Long",
  "MaxKey",
  "MinKey",
  "ObjectId",
  "Timestamp",
]

/** Options for {@link generateTypes}. */
export interface GenerateOptions {
  /** The module the BSON classes are imported from. Defaults to `@canopy/client`. */
  readonly importFrom?: string
  /** A note for the header, for example the role the types were generated for. */
  readonly note?: string
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

function key(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name)
}

function scalar(shape: Extract<Shape, { kind: "scalar" }>): string {
  if (shape.type === "string" && shape.values !== undefined && shape.values.length > 0)
    return shape.values.map((value) => JSON.stringify(value)).join(" | ")
  return SCALAR_TYPES[shape.type]
}

function typeOf(shape: Shape, indent: string): string {
  switch (shape.kind) {
    case "any":
      return "unknown"
    case "scalar":
      return scalar(shape)
    case "array": {
      const item = typeOf(shape.items, indent)
      return /^[A-Za-z0-9_]+$/.test(item) ? `${item}[]` : `(${item})[]`
    }
    case "union": {
      const parts = shape.of.flatMap((member) =>
        member.kind === "scalar" ? scalar(member).split(" | ") : [typeOf(member, indent)],
      )
      return [...new Set(parts)].join(" | ")
    }
    case "object":
      return objectType(shape, indent, false)
  }
}

function objectType(shape: ObjectShape, indent: string, optionalId: boolean): string {
  const names = Object.keys(shape.fields).sort()
  if (names.length === 0) return "Record<string, unknown>"
  const inner = `${indent}  `
  const lines = names.map((name) => {
    const field = shape.fields[name]
    const optional = field?.required !== true || (optionalId && name === "_id")
    return `${inner}${key(name)}${optional ? "?" : ""}: ${typeOf(field?.shape ?? { kind: "any" }, inner)}`
  })
  return `{\n${lines.join("\n")}\n${indent}}`
}

/** `todo_items` and `todo-items` become `TodoItems`; names that are not valid identifiers give `undefined`. */
function pascalCase(name: string): string | undefined {
  const words = name.split(/[^A-Za-z0-9]+/).filter((word) => word !== "")
  const joined = words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("")
  return /^[A-Z][A-Za-z0-9]*$/.test(joined) ? joined : undefined
}

/**
 * One `export type Todos = Database["todos"]["Document"]` alias per collection, skipping names that are not
 * identifiers and names that two collections (or `Database`) would share.
 */
function rowAliases(names: readonly string[]): string[] {
  const byAlias = new Map<string, string[]>()
  for (const name of [...names].sort()) {
    const alias = pascalCase(name)
    if (alias === undefined || alias === "Database") continue
    byAlias.set(alias, [...(byAlias.get(alias) ?? []), name])
  }
  const lines = [...byAlias]
    .filter(([, owners]) => owners.length === 1)
    .map(
      ([alias, owners]) =>
        `export type ${alias} = Database[${JSON.stringify(owners[0])}]["Document"]`,
    )
  return lines.length === 0 ? [] : ["", ...lines]
}

/**
 * Emits the `Database` interface the SDK is typed with: per collection a `Document` (a stored document) and an
 * `Insert` (the same with `_id` optional), followed by a short type alias per collection
 * (`export type Todos = Database["todos"]["Document"]`). The output depends only on the schemas, so it is stable
 * to commit and to compare in CI.
 */
export function generateTypes(
  schemas: readonly CollectionSchema[],
  options: GenerateOptions = {},
): string {
  const body = [...schemas]
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map((schema) => {
      const doc = objectType(schema.shape, "    ", false)
      const insert = objectType(schema.shape, "    ", true)
      return `  ${key(schema.name)}: {\n    Document: ${doc}\n    Insert: ${insert}\n  }`
    })
  const used = IMPORTS.filter((name) => body.some((text) => new RegExp(`\\b${name}\\b`).test(text)))
  const header = [
    "// Generated by canopy gen types. Do not edit.",
    ...(options.note === undefined ? [] : [`// ${options.note}`]),
  ]
  const imports =
    used.length === 0
      ? []
      : [
          `import type { ${used.join(", ")} } from ${JSON.stringify(options.importFrom ?? "@canopy/client")}`,
          "",
        ]
  const aliases = rowAliases(schemas.map((schema) => schema.name))
  return `${[...header, ...imports, "export interface Database {", ...body, "}", ...aliases].join("\n")}\n`
}
