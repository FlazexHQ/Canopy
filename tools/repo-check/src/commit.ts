import { findDashesInText } from "./dashes.ts"

/** Commit types accepted in a Conventional Commits header. */
export const COMMIT_TYPES: readonly string[] = [
  "build",
  "chore",
  "ci",
  "docs",
  "feat",
  "fix",
  "perf",
  "refactor",
  "revert",
  "style",
  "test",
]

/** The longest header line accepted, matching the commitlint default. */
export const MAX_HEADER_LENGTH = 100

const HEADER = /^(?<type>[a-z]+)(?:\((?<scope>[^()\s]+)\))?(?<breaking>!)?: (?<subject>.+)$/
const SCOPE = /^[a-z0-9]+(?:[-./][a-z0-9]+)*$/
const SIGN_OFF = /^Signed-off-by: [^<>\n]+ <[^<>\s@]+@[^<>\s@]+>$/m
const SCISSORS = /^# -+ >8 -+$/m

/**
 * Validates a commit message against the repository rules: a Conventional Commits header, a blank
 * line before the body, a DCO `Signed-off-by` trailer, and no punctuation dashes.
 *
 * Git comment lines (starting with `#`) and everything below a scissors line are ignored, as
 * `git commit` strips them. Merge commits generated by Git are exempt from the header rules.
 *
 * @returns the problems found; an empty array means the message is valid.
 */
export function checkCommitMessage(raw: string): string[] {
  const message = clean(raw)
  if (message === "") return ["the commit message is empty"]
  const lines = message.split("\n")
  const header = lines[0] ?? ""
  const problems: string[] = []

  if (!header.startsWith("Merge ")) {
    problems.push(...checkHeader(header))
    if (lines.length > 1 && lines[1] !== "") {
      problems.push("the header must be followed by a blank line")
    }
  }
  if (!SIGN_OFF.test(message)) {
    problems.push('missing DCO sign off: add "Signed-off-by: Name <email>" (use git commit -s)')
  }
  for (const dash of findDashesInText(message)) {
    problems.push(`line ${dash.line}, column ${dash.column}: ${dash.kind} used as punctuation`)
  }
  return problems
}

function checkHeader(header: string): string[] {
  const problems: string[] = []
  if (header.length > MAX_HEADER_LENGTH) {
    problems.push(
      `the header is ${header.length} characters long; the limit is ${MAX_HEADER_LENGTH}`,
    )
  }
  const groups = HEADER.exec(header)?.groups
  if (groups === undefined) {
    problems.push('the header must look like "type(scope): subject" (Conventional Commits)')
    return problems
  }
  const { type = "", scope, subject = "" } = groups
  if (!COMMIT_TYPES.includes(type)) {
    problems.push(`unknown commit type "${type}"; use one of ${COMMIT_TYPES.join(", ")}`)
  }
  if (scope !== undefined && !SCOPE.test(scope)) {
    problems.push(`the scope "${scope}" must be lower case words joined by "-", "." or "/"`)
  }
  if (subject.trim() !== subject || subject === "") {
    problems.push("the subject must not start or end with whitespace")
  }
  if (subject.endsWith(".")) {
    problems.push("the subject must not end with a period")
  }
  return problems
}

function clean(raw: string): string {
  const normalized = raw.replace(/\r\n?/g, "\n")
  const scissors = SCISSORS.exec(normalized)
  const kept = scissors === null ? normalized : normalized.slice(0, scissors.index)
  return kept
    .split("\n")
    .filter((line) => !line.startsWith("#"))
    .map((line) => line.trimEnd())
    .join("\n")
    .trim()
}
